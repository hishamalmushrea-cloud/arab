def افحص_الفهرس(دولة):
    """E1/E2/E10: مقارنة الفهرس بملفات الوحدات."""
    for م in مجلدات_الوحدات:
        فهرس = os.path.join(مجلد_الدول, دولة, م, "README.md")
        if not os.path.isfile(فهرس):
            continue
        جدول = {}
        for سطر in اقرأ(فهرس).splitlines():
            if not سطر.strip().startswith("|"):
                continue
            خلايا = [x.strip() for x in سطر.strip().strip("|").split("|")]
            if len(خلايا) < 6 or not خلايا[0].isdigit():
                continue
            اسم = re.sub(r"^(محافظة|ولاية|منطقة|جهة|إقليم|شعبية|بلدية)\s+", "", خلايا[1]).strip()
            جدول[اسم] = {
                "مساحة": عربية_إلى_رقم(خلايا[3]),
                "سكان": عربية_إلى_رقم(خلايا[4]),
                "وحدات": عربية_إلى_رقم(خلايا[5]),
            }
        for اسم_مجلد, مسار in ملفات_الوحدات(دولة):
            نص = اقرأ(مسار)
            مفتاح = next((k for k in جدول if k.replace(" ", "_") == اسم_مجلد
                          or k == اسم_مجلد.replace("_", " ")), None)
            if not مفتاح:
                continue
            مرجع = جدول[مفتاح]
            ms = re.search(r"\*\*المساحة:\*\*\s*[~≈]?\s*([\d,٬.]+)", نص)
            if ms and مرجع["مساحة"]:
                ق = عربية_إلى_رقم(ms.group(1))
                if ق and مرجع["مساحة"] and (max(ق, مرجع["مساحة"]) / max(min(ق, مرجع["مساحة"]), 1)) > 1.15:
                    سجّل("E1", دولة, مسار,
                         f"المساحة في الملف {ق:,} كم² ≠ الفهرس {مرجع['مساحة']:,} كم² "
                         f"(فارق {max(ق, مرجع['مساحة']) / max(min(ق, مرجع['مساحة']), 1):.1f}×)")
            mv = re.search(r"(\d+)\s*(?:مديرية|مديريات|قضاء|أقضية|دائرة|دوائر|معتمدية|معتمديات|ولاية|ولايات|مركز|مراكز)", نص)
            if mv and مرجع["وحدات"]:
                ق = int(mv.group(1))
                if ق != مرجع["وحدات"] and ق < 400:
                    سجّل("E10", دولة, مسار,
                         f"عدد الوحدات الفرعية في الملف {ق} ≠ الفهرس {مرجع['وحدات']}")


def افحص_الألقاب(دولة):
    """E3: لقب حصري منسوب لأكثر من وحدة."""
    حاملو = collections.defaultdict(list)
    for _, مسار in ملفات_الوحدات(دولة):
        نص = اقرأ(مسار)
        for نمط, وسم in ألقاب_حصرية:
            for سطر in نص.splitlines():
                if re.search(نمط, سطر) and not re.search(
                        r"ليست\s+أكبر|ليست\s+أصغر|ليست\s+\*\*أكبر|ليست\s+\*\*أصغر|"
                        r"ثاني أكبر|ثالث أكبر|رابع أكبر|من أكبر|"
                        r"\*\*ليست\*\*|بعد\s+حضرموت|الأكبر\b.*مقابل|أصغر منها|أكبر منها", سطر):
                    حاملو[وسم].append(os.path.relpath(مسار, الجذر))
                    break
    for وسم, قائمة in حاملو.items():
        if len(set(قائمة)) > 1:
            سجّل("E3", دولة, قائمة[0],
                 f"اللقب الحصري «{وسم}» منسوب إلى {len(set(قائمة))} وحدات: "
                 + " · ".join(os.path.basename(x) for x in sorted(set(قائمة))))


def افحص_العاصمة(دولة):
    """E5: 'عاصمة الدولة' في ملف وحدة ليست العاصمة."""
    مسموح = العواصم.get(دولة, [])
    for اسم, مسار in ملفات_الوحدات(دولة) + ملفات_المدن(دولة):
        نظيف = اسم.replace("_", " ")
        if any(ع in نظيف for ع in مسموح):
            continue
        for i, سطر in enumerate(اقرأ(مسار).splitlines(), 1):
            نمط_عاصمة = rf"عاصمة\s+{re.escape(دولة.replace('_', ' '))}"
            استثناء = re.search(
                نمط_عاصمة + r"\s*(?:القديمة|الفرعونية|القديم|الجديدة|الإدارية|التاريخية)"
                r"|(?:القديمة|الفرعونية|الجديدة|الإدارية)\s*\)?\s*$"
                # سياق تاريخي: «عاصمة مصر في عصر الأسرة 21» / «عاصمة الإقليم»
                r"|عاصمة\s+\S+\s+(?:في|خلال)\s+(?:عصر|عهد|فترة)"
                r"|عاصمة\s+(?:الإقليم|إقليم|مركز|المملكة)"
                r"|الأسرة\s*\d+|الدولة (?:القديمة|الوسطى|الحديثة)", سطر)
            نفي = re.search(r"ليست\s+عاصمة|ليست\s+\*\*عاصمة|العاصمة الدستورية|"
                            r"ليست أكبر|ليست أصغر|لا تُخلط|وليست", سطر)
            if re.search(نمط_عاصمة, سطر) and not استثناء and not نفي:
                سجّل("E5", دولة, مسار,
                     f"«عاصمة {دولة}» في ملف «{نظيف}» وهي ليست العاصمة — "
                     f"{سطر.strip()[:90]}…", i)


def افحص_التسرّب(دولة):
    """E6: مصطلح من إقليم آخر."""
    for _, مسار in list(ملفات_الوحدات(دولة)) + list(ملفات_المدن(دولة)) + \
            [(None, os.path.join(مجلد_الدول, دولة, f))
             for f in os.listdir(os.path.join(مجلد_الدول, دولة))
             if f.endswith(".md")]:
        نص = اقرأ(مسار)
        for i, سطر in enumerate(نص.splitlines(), 1):
            for نمط, دول in تسرّب_إقليمي.items():
                if دولة in دول:
                    continue
                m = re.search(نمط, سطر)
                # تجاهل سياق النفي/التمييز: «ليست معتمدية تونسية» «لا يُخلط بـ»
                if m and not re.search(
                        r"ليست?|ليسوا|لا\s+يُخلط|لا\s+تُخلط|بخلاف|مقابل|وليس|دون\s+خلط|"
                        r"حُذف|أُبدل|تسرّب|لا علاقة|سجل التصحيح|ما كان مكتوبًا",
                        سطر):
                    سجّل("E6", دولة, مسار,
                         f"مصطلح «{m.group(0).strip()}» لا ينتمي إلى {دولة} — "
                         f"{سطر.strip()[:90]}…", i)


def افحص_قائمة_المراقبة(دولة=None):
    """E9: أسماء أماكن غير موثَّقة."""
    for د, مسار in كل_الملفات(دولة):
        نص = اقرأ(مسار)
        for i, سطر in enumerate(نص.splitlines(), 1):
            if re.search(r"تصنيف رواية|لم أجد|فحُذفت|قائمة المراقبة|لا في |"
                         r"لا وجود|أُبدل|حُذف|ما كان مكتوبًا|سجل التصحيح|لا سند|الصواب", سطر):
                continue
            for اسم in قائمة_مراقبة:
                if اسم in سطر:
                    سجّل("E9", د or "—", مسار,
                         f"اسم في قائمة المراقبة «{اسم}» (يلزم مصدر أو حذف) — "
                         f"{سطر.strip()[:80]}…", i)


def افحص_القوالب(دولة=None, حد=4):
    """E4: جملة طويلة مكرَّرة حرفيًا في أكثر من `حد` ملفات."""
    سطور = collections.defaultdict(set)
    for د, مسار in كل_الملفات(دولة):
        for سطر in اقرأ(مسار).splitlines():
            s = سطر.strip()
            if len(s) > 90 and not s.startswith("|"):
                سطور[s].add(os.path.relpath(مسار, الجذر))
    for س, ملفات in sorted(سطور.items(), key=lambda x: -len(x[1])):
        if len(ملفات) > حد:
            سجّل("E4", دولة or "—", sorted(ملفات)[0],
                 f"جملة مكرَّرة في {len(ملفات)} ملفًا: «{س[:80]}…»")


def افحص_السنوات(دولة=None):
    """E7: رقم سكاني بلا سنة."""
    for د, مسار in كل_الملفات(دولة):
        for i, سطر in enumerate(اقرأ(مسار).splitlines(), 1):
            if re.search(r"\*\*السكان[^:]*:\*\*", سطر) and not re.search(r"(19|20)\d\d", سطر):
                سجّل("E7", د or "—", مسار,
                     f"رقم سكاني بلا سنة — {سطر.strip()[:80]}…", i)


def افحص_المصادر(دولة=None):
    """E8: ملف وحدة/مدينة بلا قسم مصادر."""
    for د, مسار in كل_الملفات(دولة):
        نسبي = os.path.relpath(مسار, الجذر)
        if not any(f"/{m}/" in f"/{نسبي}" for m in مجلدات_الوحدات + ("المدن",)):
            continue
        if os.path.basename(مسار) == "README.md":
            continue
        نص = اقرأ(مسار)
        if "المصادر" not in نص and "المصدر" not in نص and "مصادر:" not in نص:
            سجّل("E8", د or "—", مسار, "لا يوجد قسم مصادر في الملف")


