def اقرأ(مسار):
    with open(مسار, encoding="utf-8") as f:
        return f.read()


def ملفات_الوحدات(دولة):
    """يعيد [(اسم_الوحدة, المسار)] لكل وحدة إدارية عُليا في الدولة."""
    نتيجة = []
    for م in مجلدات_الوحدات:
        جذر = os.path.join(مجلد_الدول, دولة, م)
        if not os.path.isdir(جذر):
            continue
        for اسم in sorted(os.listdir(جذر)):
            د = os.path.join(جذر, اسم)
            if os.path.isdir(د):
                for f in os.listdir(د):
                    if f.endswith(".md"):
                        نتيجة.append((اسم, os.path.join(د, f)))
    return نتيجة


def ملفات_المدن(دولة):
    جذر = os.path.join(مجلد_الدول, دولة, "المدن")
    نتيجة = []
    if os.path.isdir(جذر):
        for اسم in sorted(os.listdir(جذر)):
            د = os.path.join(جذر, اسم)
            if os.path.isdir(د):
                for f in os.listdir(د):
                    if f.endswith(".md"):
                        نتيجة.append((اسم, os.path.join(د, f)))
    return نتيجة


def كل_الملفات(دولة=None):
    for جذر, _, أسماء in os.walk(الجذر):
        if ".git" in جذر or "/scripts" in جذر:
            continue
        # وثائق منهجية/تقارير تتحدث *عن* الأخطاء ولا تقع فيها
        مستثنى = ("تقرير_مراجعة_مطابقة_البرومبت.md", "02_منهجية_المصادر_والتحقق.md",
                   "00_الخطة_التنفيذية.md")
        for اسم in أسماء:
            if not اسم.endswith(".md") or اسم in مستثنى:
                continue
            م = os.path.join(جذر, اسم)
            د = None
            جزء = os.path.relpath(م, الجذر).split(os.sep)
            if len(جزء) > 1 and جزء[0] == "الدول":
                د = جزء[1]
            if دولة and د != دولة:
                continue
            yield د, م


