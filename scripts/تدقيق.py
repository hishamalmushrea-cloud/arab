def عربية_إلى_رقم(نص):
    """يحوّل '12,605' أو '~2,858' إلى عدد صحيح؛ يعيد None عند الفشل."""
    if نص is None:
        return None
    نص = نص.replace(",", "").replace("٬", "").replace("~", "").strip()
    نص = re.sub(r"[^\d.]", "", نص)
    if not نص:
        return None
    try:
        return int(float(نص))
    except ValueError:
        return None


class خطأ:
    def __init__(self, صنف, دولة, ملف, رسالة, سطر=None):
        self.صنف, self.دولة, self.ملف, self.رسالة, self.سطر = صنف, دولة, ملف, رسالة, سطر

    def __str__(self):
        موضع = f"{self.ملف}:{self.سطر}" if self.سطر else self.ملف
        return f"[{self.صنف}] {self.دولة} | {موضع}\n      {self.رسالة}"


الأخطاء = []


def سجّل(صنف, دولة, ملف, رسالة, سطر=None):
    الأخطاء.append(خطأ(صنف, دولة, os.path.relpath(ملف, الجذر), رسالة, سطر))


